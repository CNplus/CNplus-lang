"""倒序的跨后端类型、返回值与诊断合同。"""
import pytest

from cnplus.backends.注册表 import 对拍后端们
from cnplus.checker import 检查
from cnplus.parser.parser import 解析
from cnplus.source import 源文件


@pytest.mark.parametrize(("源码", "调用行", "调用文字"), [
    ('打印(倒序({"甲": 1}))', 1, '倒序({"甲": 1})'),
    ('设 数据 = {"甲": 1}\n打印(数据.倒序())', 2, '数据.倒序()'),
    ('打印(倒序(123))', 1, '倒序(123)'),
    ('打印(倒序(真))', 1, '倒序(真)'),
    ('打印(倒序(1.5))', 1, '倒序(1.5)'),
    ('打印(倒序(空))', 1, '倒序(空)'),
    ('打印(倒序(倒序))', 1, '倒序(倒序)'),
    ('设 反过来 = 倒序\n打印(反过来(真))', 2, '反过来(真)'),
    ('类 学生\n    初始化(名字)\n        自己.名字 = 名字\n打印(倒序(学生))',
     4, '倒序(学生)'),
    ('类 学生\n    初始化(名字)\n        自己.名字 = 名字\n打印(倒序(学生("甲")))',
     4, '倒序(学生("甲"))'),
])
def test_倒序非法类型诊断三层一致(源码: str, 调用行: int, 调用文字: str):
    for 登记 in 对拍后端们():
        源 = 源文件(源码, "t.cnp")
        程, 袋 = 解析(源)
        检查(程, 袋)
        assert not 袋.有错

        后 = 登记.后端类()
        后.执行(程, 源, 袋)

        assert len(袋.条目) == 1, 登记.名称
        诊 = 袋.条目[0]
        assert 诊.码 == "CN0303", 登记.名称
        assert 诊.消息 == "倒序只接受列表或文字", 登记.名称
        assert 诊.解释 == "倒序会返回和输入相同类型的新值", 登记.名称
        assert 诊.提示 == '传入列表或文字；文字也可以写 "甲😀乙"[::-1]', 登记.名称
        行文字 = 源码.splitlines()[调用行 - 1]
        起列 = 行文字.index(调用文字) + 1
        止列 = 起列 + len(调用文字)
        assert (诊.跨.起.行, 诊.跨.起.列) == (调用行, 起列), 登记.名称
        assert 诊.跨.止.行 == 调用行, 登记.名称
        assert 起列 < 诊.跨.止.列 <= 止列, 登记.名称
        assert getattr(后, "输出行", []) == [], 登记.名称
        if 登记.是子进程:
            assert getattr(后, "最后退出码", None) != 0, 登记.名称
            错误输出 = getattr(后, "最后错误输出", "")
            assert "CN0303" in 错误输出, 登记.名称
            assert "CN9001" not in 错误输出, 登记.名称
