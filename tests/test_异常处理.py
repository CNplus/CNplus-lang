"""v0.7.0 测试：异常处理（尝试 / 捕获 / 最后 / 抛出）。

核心仍是对拍：两后端输出必须逐字一致，包括捕获到的错误文本。
重点覆盖：最后 必须在任何情况下执行（正常、被捕获、错误上抛、返回穿过）。
"""
import pytest

from cnplus.backends.python_emit import Python转译后端
from cnplus.backends.treewalk import 树遍历后端
from cnplus.checker import 检查
from cnplus.parser.parser import 解析
from cnplus.source import 源文件


def _跑(码: str, 后端类):
    源 = 源文件(码, "t.cnp")
    程, 袋 = 解析(源)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    检查(程, 袋)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    输出 = []
    后端类(输出=输出.append).执行(程, 源, 袋)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    return 输出, []


def 对拍(码: str) -> list[str]:
    树, 树错 = _跑(码, 树遍历后端)
    译, 译错 = _跑(码, Python转译后端)
    assert 树错 == [] and 译错 == [], f"不该报错：树{树错} 译{译错}"
    assert 树 == 译, f"两后端不一致（语义泄漏）\n树:{树}\n译:{译}"
    return 树


# ==================== 基本捕获 ====================

def test_捕获抛出的错误():
    码 = '尝试\n    抛出 "坏了"\n捕获 错\n    打印(@"接住：{错}")'
    assert 对拍(码) == ["接住：坏了"]


def test_没出错时不进捕获():
    码 = '尝试\n    打印("正常")\n捕获 错\n    打印("不该看到")'
    assert 对拍(码) == ["正常"]


def test_捕获库错误():
    码 = '尝试\n    设 x = 整数("abc")\n    打印("不该到这")\n捕获 错\n    打印("兜住了")'
    assert 对拍(码) == ["兜住了"]


def test_捕获到的错误文本两后端一致():
    """整数转换失败的文本必须逐字相同（对齐过的常见错误）。"""
    码 = '尝试\n    整数("abc")\n捕获 错\n    打印(错)'
    assert 对拍(码) == ["没法把 abc 变成整数"]


def test_捕获不写变量():
    码 = '尝试\n    抛出 "x"\n捕获\n    打印("接住但不关心内容")'
    assert 对拍(码) == ["接住但不关心内容"]


# ==================== 最后 ====================

def test_最后总会执行_正常():
    码 = '尝试\n    打印("主体")\n最后\n    打印("最后")'
    assert 对拍(码) == ["主体", "最后"]


def test_最后总会执行_出错被捕获():
    码 = '尝试\n    抛出 "e"\n捕获 错\n    打印("捕获")\n最后\n    打印("最后")'
    assert 对拍(码) == ["捕获", "最后"]


def test_最后在返回穿过时执行():
    码 = ('函数 测试()\n    尝试\n        返回 "结果"\n    最后\n        打印("最后先跑")\n'
          '打印(测试())')
    assert 对拍(码) == ["最后先跑", "结果"]


def test_只有最后没有捕获_错误上抛():
    """内层只有最后，错误应先跑最后再上抛给外层捕获。"""
    码 = ('尝试\n    尝试\n        抛出 "内层"\n    最后\n        打印("内层最后")\n'
          '捕获 错\n    打印(@"外层接住：{错}")')
    assert 对拍(码) == ["内层最后", "外层接住：内层"]


# ==================== 未捕获的错误 ====================

def test_未捕获的抛出报CN0311():
    for 后 in (树遍历后端, Python转译后端):
        _, 错 = _跑('抛出 "没人接"', 后)
        assert "CN0311" in 错


def test_抛出非文字():
    码 = '尝试\n    抛出 42\n捕获 错\n    打印(错)'
    assert 对拍(码) == ["42"]


# ==================== 嵌套与循环 ====================

def test_循环里捕获继续():
    码 = ('遍历 [1, 0, 2] 每个 n\n    尝试\n        打印(10 / n)\n    捕获 错\n        打印("跳过零")')
    assert 对拍(码) == ["10.0", "跳过零", "5.0"]


def test_捕获后程序继续():
    码 = ('尝试\n    抛出 "e"\n捕获 错\n    打印("处理完")\n打印("继续往下")')
    assert 对拍(码) == ["处理完", "继续往下"]


# ==================== 综合 ====================

def test_综合_安全询问():
    码 = '''函数 安全转数(文字)
    尝试
        返回 整数(文字), 真
    捕获 错
        返回 0, 假

设 值, 成功 = 安全转数("42")
打印(@"{值} {成功}")
设 值2, 成功2 = 安全转数("abc")
打印(@"{值2} {成功2}")
'''
    assert 对拍(码) == ["42 真", "0 假"]
