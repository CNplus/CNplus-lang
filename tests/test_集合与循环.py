"""v0.4.0 新特性测试：列表、字典、遍历、跳出/继续、幂、内置函数库。

核心仍是**对拍**：每个特性都在树遍历后端和转译后端各跑一遍，
输出必须逐字一致 —— 这是防语义泄漏的铁证。
"""
import pytest

from cnplus.backends.python_emit import Python转译后端
from cnplus.backends.treewalk import 树遍历后端
from cnplus.checker import 检查
from cnplus.parser.parser import 解析
from cnplus.source import 源文件


def _跑(码: str, 后端类):
    源 = 源文件(码, "t.cnp")
    程, 袋 = 解析(源)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    检查(程, 袋)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    输出 = []
    后端类(输出=输出.append).执行(程, 源, 袋)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    return 输出, []


def 对拍(码: str) -> list[str]:
    """两后端跑一遍，断言一致，返回输出。"""
    树, 树错 = _跑(码, 树遍历后端)
    译, 译错 = _跑(码, Python转译后端)
    assert 树错 == [] and 译错 == [], f"不该报错：树{树错} 译{译错}"
    assert 树 == 译, f"两后端输出不一致（语义泄漏！）\n树:{树}\n译:{译}"
    return 树


# ==================== 列表 ====================

def test_列表字面量与显示():
    assert 对拍('打印([1, 2, 3])') == ["[1, 2, 3]"]
    assert 对拍('打印([])') == ["[]"]


def test_列表索引():
    assert 对拍('设 a = [10, 20, 30]\n打印(a[0])\n打印(a[2])') == ["10", "30"]


def test_列表索引赋值():
    assert 对拍('设 a = [1, 2, 3]\na[1] = 99\n打印(a)') == ["[1, 99, 3]"]


def test_列表越界报错():
    for 后 in (树遍历后端, Python转译后端):
        _, 错 = _跑('设 a = [1, 2]\n打印(a[5])', 后)
        assert "CN0308" in 错


def test_嵌套列表():
    assert 对拍('设 m = [[1, 2], [3, 4]]\n打印(m[1][0])') == ["3"]


# ==================== 字典 ====================

def test_字典字面量():
    assert 对拍('设 d = {"名": "小明", "岁": 18}\n打印(d["名"])\n打印(d["岁"])') \
        == ["小明", "18"]


def test_字典赋值新键():
    assert 对拍('设 d = {}\nd["a"] = 1\n打印(d)') == ["{a: 1}"]


def test_字典缺键报错():
    for 后 in (树遍历后端, Python转译后端):
        _, 错 = _跑('设 d = {"a": 1}\n打印(d["b"])', 后)
        assert "CN0308" in 错


# ==================== 遍历 ====================

def test_遍历列表():
    assert 对拍('对于 x 在 [1, 2, 3]\n    打印(x)') == ["1", "2", "3"]


def test_遍历字符串():
    assert 对拍('对于 字 在 "abc"\n    打印(字)') == ["a", "b", "c"]


def test_遍历范围():
    assert 对拍('对于 i 在 范围(3)\n    打印(i)') == ["0", "1", "2"]


def test_遍历不可迭代报错():
    for 后 in (树遍历后端, Python转译后端):
        _, 错 = _跑('对于 x 在 42\n    打印(x)', 后)
        assert "CN0309" in 错


def test_遍历变量作用域():
    """遍历变量在循环外不可见。"""
    for 后 in (树遍历后端, Python转译后端):
        _, 错 = _跑('对于 x 在 [1]\n    打印(x)\n打印(x)', 后)
        assert "CN0302" in 错


# ==================== 跳出 / 继续 ====================

def test_跳出():
    assert 对拍('对于 i 在 范围(10)\n    如果 i == 3\n        跳出\n    打印(i)') \
        == ["0", "1", "2"]


def test_继续():
    assert 对拍('对于 i 在 范围(5)\n    如果 i == 2\n        继续\n    打印(i)') \
        == ["0", "1", "3", "4"]


def test_循环里跳出():
    码 = '设 i = 0\n循环 真\n    如果 i >= 3\n        跳出\n    打印(i)\n    i = i + 1'
    assert 对拍(码) == ["0", "1", "2"]


def test_嵌套遍历():
    码 = '对于 i 在 [1, 2]\n    对于 j 在 [10, 20]\n        打印(文本(i) + "-" + 文本(j))'
    assert 对拍(码) == ["1-10", "1-20", "2-10", "2-20"]


# ==================== 幂 ====================

def test_幂():
    assert 对拍('打印(2 ** 10)') == ["1024"]


def test_幂右结合():
    # 2**(3**2) = 2**9 = 512
    assert 对拍('打印(2 ** 3 ** 2)') == ["512"]


def test_幂优先级高于乘():
    assert 对拍('打印(3 * 2 ** 2)') == ["12"]


# ==================== 内置函数库 ====================

@pytest.mark.parametrize("码,期望", [
    ('打印(求和([1, 2, 3, 4]))', ["10"]),
    ('打印(最大([3, 7, 2]))', ["7"]),
    ('打印(最小([3, 7, 2]))', ["2"]),
    ('打印(最大(3, 9, 1))', ["9"]),
    ('打印(排序([3, 1, 2]))', ["[1, 2, 3]"]),
    ('打印(倒序([1, 2, 3]))', ["[3, 2, 1]"]),
    ('打印(绝对值(-5))', ["5"]),
    ('打印(平方根(16))', ["4.0"]),
    ('打印(四舍五入(3.7))', ["4"]),
    ('打印(连接(["a", "b"], "-"))', ["a-b"]),
    ('打印(包含([1, 2], 2))', ["真"]),
    ('打印(大写("hi"))', ["HI"]),
    ('打印(替换("aaa", "a", "b"))', ["bbb"]),
    ('打印(分割("a,b,c", ","))', ["[a, b, c]"]),
    ('打印(去空白("  hi  "))', ["hi"]),
    ('打印(开头是("hello", "he"))', ["真"]),
])
def test_内置函数(码, 期望):
    assert 对拍(码) == 期望


def test_列表可变操作():
    码 = '设 a = [1, 2]\n追加(a, 3)\n打印(a)\n移除(a, 1)\n打印(a)'
    assert 对拍(码) == ["[1, 2, 3]", "[2, 3]"]


def test_字典操作():
    码 = ('设 d = {"a": 1, "b": 2}\n打印(排序(键们(d)))\n'
          '打印(有键(d, "a"))\n打印(有键(d, "z"))')
    assert 对拍(码) == ["[a, b]", "真", "假"]


# ==================== 综合：一个真实点的程序 ====================

def test_综合_统计成绩():
    码 = '''设 成绩 = {"小明": 85, "小红": 92, "小刚": 78}
设 总分 = 0
对于 名 在 键们(成绩)
    总分 = 总分 + 成绩[名]
设 平均 = 总分 / 长度(成绩)
打印("总分：" + 文本(总分))
打印("平均：" + 文本(平均))
设 最高 = 最大(值们(成绩))
打印("最高分：" + 文本(最高))
'''
    assert 对拍(码) == ["总分：255", "平均：85.0", "最高分：92"]
