"""v0.7.1 回归测试：两个由「写真实程序」暴露的 bug。

1. 索引复合赋值：字典[键] += 1 / 列表[i] += 1
   —— 之前只支持普通变量 x += 1，统计类代码高频踩到。
2. 内置名遮蔽的两后端一致性：函数 查找(...) 覆盖内置「查找」
   —— 之前转译后端报 CN0307、树遍历后端不报，同一段代码两后端结果不同。
"""
import pytest

from cnplus.backends.python_emit import Python转译后端
from cnplus.backends.treewalk import 树遍历后端
from cnplus.checker import 检查
from cnplus.parser.parser import 解析
from cnplus.source import 源文件


def _跑(码: str, 后端类):
    源 = 源文件(码, "t.cnp")
    程, 袋 = 解析(源)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    检查(程, 袋)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    输出 = []
    后端类(输出=输出.append).执行(程, 源, 袋)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    return 输出, []


def 对拍(码: str) -> list[str]:
    树, 树错 = _跑(码, 树遍历后端)
    译, 译错 = _跑(码, Python转译后端)
    assert 树错 == [] and 译错 == [], f"不该报错：树{树错} 译{译错}"
    assert 树 == 译, f"两后端不一致（语义泄漏）\n树:{树}\n译:{译}"
    return 树


# ==================== 索引复合赋值 ====================

def test_字典元素自增():
    码 = '设 d = {"a": 1}\nd["a"] += 1\n打印(d["a"])'
    assert 对拍(码) == ["2"]


def test_列表元素自增():
    码 = '设 a = [10, 20]\na[0] += 5\n打印(a)'
    assert 对拍(码) == ["[15, 20]"]


@pytest.mark.parametrize("符,期望", [
    ("+=", "15"), ("-=", "5"), ("*=", "50"), ("/=", "2.0"),
])
def test_索引四种复合赋值(符, 期望):
    码 = f'设 a = [10]\na[0] {符} 5\n打印(a[0])'
    assert 对拍(码) == [期望]


def test_字典元素拼接文字():
    码 = '设 d = {"s": "你"}\nd["s"] += "好"\n打印(d["s"])'
    assert 对拍(码) == ["你好"]


def test_嵌套索引复合赋值():
    码 = '设 m = [[1, 2], [3, 4]]\nm[1][0] += 100\n打印(m)'
    assert 对拍(码) == ["[[1, 2], [103, 4]]"]


def test_统计模式():
    """这就是暴露 bug 的真实场景：分组计数。"""
    码 = '''设 计数 = {}
遍历 ["甲", "乙", "甲", "甲"] 每个 x
    如果 有标签(计数, x)
        计数[x] += 1
    否则
        计数[x] = 1
打印(计数["甲"])
打印(计数["乙"])
'''
    assert 对拍(码) == ["3", "1"]


# ==================== 内置名遮蔽 ====================

def test_用户函数可覆盖内置名():
    """函数 查找 覆盖内置「查找」，两后端都该允许且行为一致。"""
    码 = '函数 查找(x)\n    返回 填"自定义查找 {x}"\n打印(查找(7))'
    assert 对拍(码) == ["自定义查找 7"]


def test_覆盖内置后原内置不可用():
    """覆盖了就是覆盖了 —— 两后端一致地用新定义。"""
    码 = '函数 长度(x)\n    返回 999\n打印(长度([1, 2, 3]))'
    assert 对拍(码) == ["999"]


def test_变量也可遮蔽内置名():
    码 = '设 查找 = 42\n打印(查找)'
    assert 对拍(码) == ["42"]


# ==================== 重复声明仍要报错 ====================

def test_真重复声明静态报错():
    """把运行期查重挪走后，静态检查必须仍然抓到真重复。"""
    源 = 源文件("设 x = 1\n设 x = 2", "t.cnp")
    程, 袋 = 解析(源)
    检查(程, 袋)
    assert "CN0307" in [d.码 for d in 袋]


def test_函数内重复声明静态报错():
    源 = 源文件("函数 f()\n    设 y = 1\n    设 y = 2", "t.cnp")
    程, 袋 = 解析(源)
    检查(程, 袋)
    assert "CN0307" in [d.码 for d in 袋]
