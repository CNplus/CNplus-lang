"""v0.5.0 新特性测试：否则如果、默认参数、关键字参数、成员方法调用、自增/复合赋值。

核心仍是对拍：每个特性都在两后端各跑一遍，输出必须逐字一致。
"""
import pytest

from cnplus.backends.python_emit import Python转译后端
from cnplus.backends.treewalk import 树遍历后端
from cnplus.checker import 检查
from cnplus.parser.parser import 解析
from cnplus.source import 源文件


def _跑(码: str, 后端类):
    源 = 源文件(码, "t.cnp")
    程, 袋 = 解析(源)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    检查(程, 袋)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    输出 = []
    后端类(输出=输出.append).执行(程, 源, 袋)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    return 输出, []


def 对拍(码: str) -> list[str]:
    树, 树错 = _跑(码, 树遍历后端)
    译, 译错 = _跑(码, Python转译后端)
    assert 树错 == [] and 译错 == [], f"不该报错：树{树错} 译{译错}"
    assert 树 == 译, f"两后端输出不一致（语义泄漏！）\n树:{树}\n译:{译}"
    return 树


# ==================== 否则如果 ====================

def test_否则如果_三档():
    模板 = '设 分 = {}\n如果 分 >= 90\n    打印("优")\n否则 如果 分 >= 60\n    打印("及格")\n否则\n    打印("不及格")'
    assert 对拍(模板.format(95)) == ["优"]
    assert 对拍(模板.format(75)) == ["及格"]
    assert 对拍(模板.format(30)) == ["不及格"]


def test_否则如果_多级链():
    码 = ('设 x = 3\n如果 x == 1\n    打印("一")\n否则 如果 x == 2\n    打印("二")\n'
          '否则 如果 x == 3\n    打印("三")\n否则\n    打印("其他")')
    assert 对拍(码) == ["三"]


# ==================== 默认参数 ====================

def test_默认参数_用默认():
    码 = '函数 问候(名字, 招呼 = "你好")\n    返回 招呼 + "，" + 名字\n打印(问候("小明"))'
    assert 对拍(码) == ["你好，小明"]


def test_默认参数_覆盖默认():
    码 = '函数 问候(名字, 招呼 = "你好")\n    返回 招呼 + "，" + 名字\n打印(问候("小红", "早上好"))'
    assert 对拍(码) == ["早上好，小红"]


def test_默认参数_多个():
    码 = ('函数 造(a, b = 10, c = 20)\n    返回 a + b + c\n'
          '打印(造(1))\n打印(造(1, 2))\n打印(造(1, 2, 3))')
    assert 对拍(码) == ["31", "23", "6"]


def test_缺少必填参数报错():
    码 = '函数 f(a, b)\n    返回 a\nf(1)'
    for 后 in (树遍历后端, Python转译后端):
        _, 错 = _跑(码, 后)
        assert "CN0306" in 错


# ==================== 关键字参数 ====================

def test_关键字参数():
    码 = ('函数 问候(名字, 招呼 = "你好")\n    返回 招呼 + "，" + 名字\n'
          '打印(问候(招呼 = "晚上好", 名字 = "小刚"))')
