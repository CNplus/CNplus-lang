# ==================== 成员方法调用 ====================

def test_列表方法():
    码 = '设 a = [3, 1, 2]\na.追加(9)\n打印(a)\n打印(a.包含(9))'
    assert 对拍(码) == ["[3, 1, 2, 9]", "真"]


def test_字符串方法():
    assert 对拍('打印("HELLO".小写())') == ["hello"]
    assert 对拍('打印("a,b,c".分割(","))') == ["[a, b, c]"]


def test_字典方法():
    码 = '设 d = {"a": 1}\n打印(d.有标签("a"))\n打印(排序(d.所有标签()))'
    assert 对拍(码) == ["真", "[a]"]


def test_方法与函数等价():
    """名单.追加(x) 和 追加(名单, x) 应完全一样。"""
    码1 = '设 a = [1]\na.追加(2)\n打印(a)'
    码2 = '设 a = [1]\n追加(a, 2)\n打印(a)'
    assert 对拍(码1) == 对拍(码2) == ["[1, 2]"]


# ==================== 自增 / 复合赋值 ====================

def test_自增自减():
    码 = '设 x = 5\nx++\n打印(x)\nx--\nx--\n打印(x)'
    assert 对拍(码) == ["6", "4"]


def test_复合赋值():
    码 = '设 x = 10\nx += 5\n打印(x)\nx -= 3\n打印(x)\nx *= 2\n打印(x)\nx /= 4\n打印(x)'
    assert 对拍(码) == ["15", "12", "24", "6.0"]


def test_复合赋值_字符串拼接():
    码 = '设 s = "你"\ns += "好"\n打印(s)'
    assert 对拍(码) == ["你好"]


def test_自增非数字报错():
    码 = '设 s = "字"\ns++'
    for 后 in (树遍历后端, Python转译后端):
        _, 错 = _跑(码, 后)
        assert "CN0303" in 错


def test_循环里自增():
    码 = '设 和 = 0\n设 i = 1\n循环 i <= 5\n    和 += i\n    i++\n打印(和)'
    assert 对拍(码) == ["15"]


# ==================== 综合 ====================

def test_综合_成绩分档():
    码 = '''函数 评级(分, 满分 = 100)
    设 比 = 分 / 满分 * 100
    如果 比 >= 90
        返回 "优"
    否则 如果 比 >= 60
        返回 "及格"
    否则
        返回 "不及格"

设 名单 = [95, 72, 40]
遍历 名单 每个 分
    打印(评级(分))
'''
    assert 对拍(码) == ["优", "及格", "不及格"]
