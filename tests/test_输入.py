"""输入功能测试：问 / 询问数值。

输入用注入的假输入序列，不碰真实标准输入。
重点覆盖真实踩过的坑：输入耗尽（EOF）时不能死循环。
"""
import pytest

from cnplus.backends.treewalk import 树遍历后端
from cnplus.checker import 检查
from cnplus.parser.parser import 解析
from cnplus.source import 源文件


def 跑(码: str, 输入行=None):
    """输入行用完后返回 None，模拟 EOF。"""
    源 = 源文件(码, "t.cnp")
    程, 袋 = 解析(源)
    检查(程, 袋)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    剩 = list(输入行 or [])

    def 喂():
        return 剩.pop(0) if 剩 else None

    输出: list[str] = []
    树遍历后端(输出=输出.append, 输入=喂).执行(程, 源, 袋)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    return 输出, []


# ==================== 问（文字） ====================

def test_询问_基本():
    出, 错 = 跑('设 名 = 询问("名字：")\n打印(@"你好，{名}")', ["小明"])
    assert 错 == [] and 出 == ["你好，小明"]


def test_询问_无提示():
    出, 错 = 跑('设 x = 询问()\n打印(x)', ["随便"])
    assert 错 == [] and 出 == ["随便"]


def test_询问_读到的是文字():
    """问 读回来的永远是文字，即使输入看着像数字。"""
    出, 错 = 跑('设 x = 询问()\n打印(类型(x))', ["123"])
    assert 错 == [] and 出 == ["字符串"]


def test_询问_输入结束给空串():
    出, 错 = 跑('设 x = 询问()\n打印(长度(x))', [])
    assert 错 == [] and 出 == ["0"]


# ==================== 询问数值 ====================

def test_询问数值_整数():
    出, 错 = 跑('设 n = 询问数值()\n打印(n + 1)', ["41"])
    assert 错 == [] and 出 == ["42"]


def test_询问数值_小数():
    出, 错 = 跑('设 n = 询问数值()\n打印(n)', ["1.5"])
    assert 错 == [] and 出 == ["1.5"]


def test_询问数值_类型是数字():
    出, 错 = 跑('设 n = 询问数值()\n打印(类型(n))', ["7"])
    assert 错 == [] and 出 == ["整数"]


def test_询问数值_输错会重询问():
    """输入 abc 后再输 5，应该拿到 5（中间提示不进输出行）。"""
    出, 错 = 跑('设 n = 询问数值()\n打印(n)', ["abc", "5"])
    assert 错 == [] and 出 == ["5"]


def test_询问数值_前后空格无妨():
    出, 错 = 跑('设 n = 询问数值()\n打印(n)', ["  8  "])
    assert 错 == [] and 出 == ["8"]


def test_询问数值_输入结束不死循环():
    """真实踩过的坑：EOF 后重试会无限循环，必须报 CN0310 而不是挂住。"""
    出, 错 = 跑('设 n = 询问数值()\n打印(n)', [])
    assert "CN0310" in 错, f"应报输入结束，实际 {错}"


def test_询问数值_一直输错到耗尽也不死循环():
    出, 错 = 跑('设 n = 询问数值()\n打印(n)', ["a", "b", "c"])
    assert "CN0310" in 错


# ==================== 组合 ====================

def test_循环里反复询问():
    码 = ('设 和 = 0\n设 i = 0\n循环 i < 3\n    和 += 询问数值()\n    i++\n打印(和)')
    出, 错 = 跑(码, ["1", "2", "3"])
    assert 错 == [] and 出 == ["6"]


def test_问的结果参与判断():
    码 = ('设 答 = 询问("继续吗？")\n如果 答 == "是"\n    打印("继续")\n否则\n    打印("停止")')
    出, 错 = 跑(码, ["是"])
    assert 错 == [] and 出 == ["继续"]
    出, 错 = 跑(码, ["否"])
    assert 错 == [] and 出 == ["停止"]


def test_询问数值参与算术():
    出, 错 = 跑('设 a = 询问数值()\n设 b = 询问数值()\n打印(@"{a} × {b} = {a * b}")',
              ["6", "7"])
    assert 错 == [] and 出 == ["6 × 7 = 42"]
