"""v0.6.0 测试：格式化字符串（填）+ 多返回值解包。

核心仍是对拍：两后端输出必须逐字一致。
"""
import pytest

from cnplus.backends.python_emit import Python转译后端
from cnplus.backends.treewalk import 树遍历后端
from cnplus.checker import 检查
from cnplus.parser.parser import 解析
from cnplus.source import 源文件


def _跑(码: str, 后端类):
    源 = 源文件(码, "t.cnp")
    程, 袋 = 解析(源)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    检查(程, 袋)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    输出 = []
    后端类(输出=输出.append).执行(程, 源, 袋)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    return 输出, []


def 对拍(码: str) -> list[str]:
    树, 树错 = _跑(码, 树遍历后端)
    译, 译错 = _跑(码, Python转译后端)
    assert 树错 == [] and 译错 == [], f"不该报错：树{树错} 译{译错}"
    assert 树 == 译, f"两后端不一致（语义泄漏）\n树:{树}\n译:{译}"
    return 树


# ==================== 格式化字符串 ====================

def test_填_基本():
    assert 对拍('设 名 = "小明"\n打印(填"你好，{名}")') == ["你好，小明"]


def test_填_多个空():
    码 = '设 a = 3\n设 b = 5\n打印(填"{a} + {b} = {a + b}")'
    assert 对拍(码) == ["3 + 5 = 8"]


def test_填_表达式():
    assert 对拍('设 年 = 18\n打印(填"明年 {年 + 1} 岁")') == ["明年 19 岁"]


def test_填_无插值():
    assert 对拍('打印(填"纯文字")') == ["纯文字"]


def test_填_函数调用():
    码 = '函数 双(x)\n    返回 x * 2\n打印(填"双倍是 {双(21)}")'
    assert 对拍(码) == ["双倍是 42"]


def test_填_列表索引():
    码 = '设 a = [10, 20]\n打印(填"第一个是 {a[0]}")'
    assert 对拍(码) == ["第一个是 10"]


def test_填_转义大括号():
    assert 对拍('打印(填"这是一对大括号：{{}}")') == ["这是一对大括号：{}"]


def test_填_各类型显示():
    # 布尔显示为 真/假，与 文本() 一致
    assert 对拍('设 x = 真\n打印(填"结果：{x}")') == ["结果：真"]
    assert 对拍('设 x = [1, 2]\n打印(填"列表：{x}")') == ["列表：[1, 2]"]


# ==================== 多返回值解包 ====================

def test_多返回值():
    码 = '函数 除(a, b)\n    返回 a // b, a % b\n设 商, 余 = 除(17, 5)\n打印(商)\n打印(余)'
    assert 对拍(码) == ["3", "2"]


def test_多返回值_三个():
    码 = ('函数 拆(x)\n    返回 x, x * 2, x * 3\n'
          '设 甲, 乙, 丙 = 拆(5)\n打印(甲)\n打印(乙)\n打印(丙)')
    assert 对拍(码) == ["5", "10", "15"]


def test_解包列表():
    assert 对拍('设 甲, 乙 = [100, 200]\n打印(甲)\n打印(乙)') == ["100", "200"]


def test_解包数量不符报错():
    for 后 in (树遍历后端, Python转译后端):
        _, 错 = _跑('设 甲, 乙 = [1, 2, 3]', 后)
        assert "CN0306" in 错


def test_解包非列表报错():
    for 后 in (树遍历后端, Python转译后端):
        _, 错 = _跑('设 甲, 乙 = 42', 后)
        assert "CN0303" in 错


def test_多返回值配合填():
    码 = ('函数 除(a, b)\n    返回 a // b, a % b\n'
          '设 商, 余 = 除(17, 5)\n打印(填"{a}".替换("a", "x"))\n' if False else
          '函数 除(a, b)\n    返回 a // b, a % b\n'
          '设 商, 余 = 除(17, 5)\n打印(填"17÷5 = {商}余{余}")')
    assert 对拍(码) == ["17÷5 = 3余2"]


# ==================== 综合 ====================

def test_综合():
    码 = '''函数 统计(数们)
    设 总 = 求和(数们)
    设 平均 = 总 / 长度(数们)
    返回 总, 平均

设 成绩 = [80, 90, 100]
设 总分, 均分 = 统计(成绩)
打印(填"总分 {总分}，平均 {均分}")
'''
    assert 对拍(码) == ["总分 270，平均 90.0"]
