"""语义约定的可执行验证 —— docs/spec/00-语义约定.md 的每条断言。

规范说什么，这里就测什么。**测的是规定的行为，不是宿主恰好的行为**
（总纲第三节「语义泄漏防御��）。
"""
import pytest

from cnplus.backends.treewalk import 树遍历后端
from cnplus.checker import 检查
from cnplus.parser.parser import 解析
from cnplus.source import 源文件


def 跑(码: str):
    """返回 (输出行, 诊断码列表)。"""
    源 = 源文件(码, "spec.cnp")
    程, 袋 = 解析(源)
    if not 袋.有错:
        检查(程, 袋)
    输出 = []
    if not 袋.有错:
        后 = 树遍历后端(输出=输出.append)
        后.执行(程, 源, 袋)
    return 输出, [d.码 for d in 袋]


def 出(码: str) -> list[str]:
    输出, 诊 = 跑(码)
    assert not 诊, f"不该有诊断，实际 {诊}"
    return 输出


def 错(码: str) -> list[str]:
    _, 诊 = 跑(码)
    assert 诊, "应该有诊断"
    return 诊


# ==================== 二、真值 ====================

@pytest.mark.parametrize("条件", ["0", "1", '""', '"字"', "1.5", "空"])
def test_非布尔条件报错(条件):
    assert "CN0301" in 错(f"如果 {条件}\n    打印(1)")


def test_布尔条件正常():
    assert 出("如果 真\n    打印(1)") == ["1"]


def test_循环条件同规则():
    assert "CN0301" in 错("循环 1\n    打印(1)")


def test_逻辑运算符两侧必须布尔():
    assert "CN0303" in 错("打印(1 与 真)")
    assert "CN0303" in 错("打印(非 1)")
    # 左侧为假时 与 的右侧被求值，仍要检查
    assert "CN0303" in 错("打印(真 与 1)")


def test_短路时未求值的一侧不检查():
    """规范第六节：短路跳过的一侧不做类型检查。

    这是短路语义的必然代价 —— 未执行的代码没有值可检查。
    """
    assert 出("打印(真 或 1)") == ["真"]
    assert 出("打印(假 与 1)") == ["假"]


# ==================== 三、相等与比较 ====================

def test_整数小数互通():
    assert 出("打印(1 == 1.0)") == ["真"]
    assert 出("打印(2 > 1.5)") == ["真"]


def test_跨类型相等报错而非返回假():
    """故意与 Python 不同：Python 返回 False，我们报错。"""
    assert "CN0303" in 错('打印(1 == "1")')
    assert "CN0303" in 错("打印(真 == 1)")


def test_空可比相等():
    assert 出("打印(空 == 空)") == ["真"]


def test_字符串可比大小():
    assert 出('打印("a" < "b")') == ["真"]


def test_跨类型比大小报错():
    assert "CN0303" in 错('打印(1 < "a")')


# ==================== 四、算术 ====================

def test_除法恒为小数():
    """故意写下来，不靠继承 Python。"""
    assert 出("打印(4 / 2)") == ["2.0"]
    assert 出("打印(7 / 2)") == ["3.5"]


def test_整除与取余():
    assert 出("打印(7 // 2)") == ["3"]
    assert 出("打印(7 % 2)") == ["1"]
    assert 出("打印(-7 // 2)") == ["-4"]  # 向下取整


def test_除以零三种都报():
    assert "CN0304" in 错("打印(1 / 0)")
    assert "CN0304" in 错("打印(1 // 0)")
    assert "CN0304" in 错("打印(1 % 0)")


def test_字符串拼接与重复():
    assert 出('打印("你" + "好")') == ["你好"]
    assert 出('打印("哈" * 3)') == ["哈哈哈"]


def test_数字加字符串报错():
    assert "CN0303" in 错('打印(1 + "a")')


def test_任意精度整数():
    assert 出("打印(99999999999999999999 * 99999999999999999999)") == \
        ["9999999999999999999800000000000000000001"]


# ==================== 五、作用域 ====================

def test_重复声明报错():
    assert "CN0307" in 错("令 x = 1\n令 x = 2")


def test_赋值未声明报错():
    assert "CN0302" in 错("x = 1")


def test_块是新作用域():
    码 = "如果 真\n    令 x = 1\n如果 真\n    令 x = 2\n打印(\"好\")"
    assert 出(码) == ["好"]


def test_闭包读外层():
    码 = "函数 外()\n    令 n = 10\n    函数 内()\n        返回 n * 2\n    返回 内()\n\n打印(外())"
    assert 出(码) == ["20"]


def test_函数前向引用():
    码 = "函数 甲()\n    返回 乙()\n\n函数 乙()\n    返回 1\n\n打印(甲())"
    assert 出(码) == ["1"]


# ==================== 六、求值顺序 ====================

def test_与短路():
    """假 与 ... 时右侧不求值 —— 右侧有错也不该触发。"""
    assert 出("打印(1 > 2 与 1 / 0 > 0)") == ["假"]


def test_或短路():
    assert 出("打印(1 < 2 或 1 / 0 > 0)") == ["真"]


# ==================== 一、显示规则 ====================

def test_布尔显示为中文():
    assert 出("打印(真)") == ["真"]
    assert 出("打印(假)") == ["假"]


def test_空显示():
    assert 出("打印(空)") == ["空"]


def test_小数保留小数点():
    assert 出("打印(3.0)") == ["3.0"]


def test_类型函数返回中文():
    assert 出("打印(类型(1))") == ["整数"]
    assert 出("打印(类型(1.5))") == ["小数"]
    assert 出('打印(类型("a"))') == ["字符串"]
    assert 出("打印(类型(真))") == ["布尔"]
    assert 出("打印(类型(空))") == ["空"]
