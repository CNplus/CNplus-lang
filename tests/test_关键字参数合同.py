@pytest.mark.parametrize(
    "调用源码",
    (
        "J.dumps(obj = {}, 未知 = 1)",
        "J.dumps(ensure_ascii = 假)",
    ),
    ids=("未知", "缺少"),
)
def test_Python导入函数的宿主参数错误诊断一致(调用源码):
    结果们 = []
    for 登记 in 对拍后端们():
        if not 登记.后端类.能力.支持导入:
            continue
        源码 = f'导入 "json" 作为 J\n{调用源码}'
        程, 后端, _输出, 袋 = _运行(源码, 登记)
        assert [诊断.码 for 诊断 in 袋] == ["CN0303"]
        诊断 = 袋.条目[0]
        assert 诊断.消息.startswith("调用出错：")
        assert 诊断.解释 == "这个库的函数被调用时出错了，多半是参数不对"
        assert 诊断.提示 == "看看传入的参数类型和数量"
        assert 诊断.跨 == _最后调用跨度(程)
        _断言子进程错误(登记, 后端, "CN0303")
        结果们.append((诊断.消息, 诊断.解释, 诊断.提示, 诊断.跨))

    assert 结果们
    assert all(结果 == 结果们[0] for 结果 in 结果们)
