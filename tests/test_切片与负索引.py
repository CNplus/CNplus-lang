"""切片与负索引 —— D-037。

语义约定（写入 docs/spec/00-语义约定.md）：
- a[起:止:步长]：左闭右开，含起不含止；省略步长等于 1
- 起、止、步长都可省略（a[1:] / a[:3] / a[:] / a[::2]）
- 负数从后往前数（a[-1] 单索引；a[-2:] / a[:-1] 切片）
- 负步长从后向前取；省略起止时从末项取到开头之前
- 切片越界自动夹紧（不报错）；单索引越界仍报 CN0308
- 列表与字符串同规则；切片产生新值，不改原值
"""
import pytest

from cnplus.backends.python_emit import Python转译后端
from cnplus.backends.treewalk import 树遍历后端
from cnplus.backends.注册表 import 对拍后端们
from cnplus.checker import 检查
from cnplus.parser.parser import 解析
from cnplus.source import 源文件


def _跑(码: str, 后端类):
    源 = 源文件(码, "t.cnp")
    程, 袋 = 解析(源)
    if 袋.有错:
        return None, [d.码 for d in 袋]
    检查(程, 袋)
    if 袋.有错:
        return None, [(d.码, d.消息) for d in 袋]
    输出 = []
    后端类(输出=输出.append).执行(程, 源, 袋)
    if 袋.有错:
        return None, [(d.码, d.消息) for d in 袋]
    return 输出, []


def 对拍(码: str) -> list[str]:
    """两后端跑一遍，断言一致，返回输出。"""
    树, 树错 = _跑(码, 树遍历后端)
    译, 译错 = _跑(码, Python转译后端)
    assert 树错 == [] and 译错 == [], f"不该报错：树{树错} 译{译错}"
    assert 树 == 译, f"两后端输出不一致（语义泄漏！）\n树:{树}\n译:{译}"
    return 树


# ==================== 单索引负数 ====================

def test_负索引_列表():
    assert 对拍('设 a = [1, 2, 3]\n打印(a[-1])') == ["3"]
    assert 对拍('设 a = [1, 2, 3]\n打印(a[-2])') == ["2"]


def test_负索引_字符串():
    assert 对拍('设 s = "你好"\n打印(s[-1])') == ["好"]


def test_负索引_越界报CN0308():
    码 = '设 a = [1, 2, 3]\n打印(a[-4])'
    for 后 in (树遍历后端, Python转译后端):
        _, 错 = _跑(码, 后)
        assert "CN0308" in [e[0] if isinstance(e, tuple) else e for e in 错]


# ==================== 切片：基本 ====================

def test_切片_左闭右开():
    assert 对拍('设 a = [1, 2, 3, 4, 5]\n打印(a[1:3])') == ["[2, 3]"]


def test_切片_省略止():
    assert 对拍('设 a = [1, 2, 3, 4, 5]\n打印(a[2:])') == ["[3, 4, 5]"]


def test_切片_省略起():
    assert 对拍('设 a = [1, 2, 3, 4, 5]\n打印(a[:2])') == ["[1, 2]"]


def test_切片_全省略():
    assert 对拍('设 a = [1, 2, 3]\n打印(a[:])') == ["[1, 2, 3]"]


def test_切片_字符串():
    assert 对拍('设 s = "你好世界"\n打印(s[1:3])') == ["好世"]


# ==================== 切片：负数 ====================

def test_切片_负起():
    assert 对拍('设 a = [1, 2, 3, 4, 5]\n打印(a[-2:])') == ["[4, 5]"]


def test_切片_负止():
    assert 对拍('设 a = [1, 2, 3, 4, 5]\n打印(a[:-1])') == ["[1, 2, 3, 4]"]


def test_切片_双负():
    assert 对拍('设 a = [1, 2, 3, 4, 5]\n打印(a[-3:-1])') == ["[3, 4]"]


# ==================== 切片：越界夹紧 ====================

def test_切片_超界夹紧():
    assert 对拍('设 a = [1, 2, 3]\n打印(a[1:99])') == ["[2, 3]"]
    assert 对拍('设 a = [1, 2, 3]\n打印(a[99:100])') == ["[]"]
    assert 对拍('设 a = [1, 2, 3]\n打印(a[-99:2])') == ["[1, 2]"]


def test_切片_起大于止得空():
    assert 对拍('设 a = [1, 2, 3]\n打印(a[2:1])') == ["[]"]


# ==================== 切片是拷贝 ====================

def test_切片_不改原值():
    码 = '''设 a = [1, 2, 3]
设 b = a[0:2]
追加(b, 99)
打印(a)
打印(b)'''
    assert 对拍(码) == ["[1, 2, 3]", "[1, 2, 99]"]


@pytest.mark.parametrize(("码", "期望位置"), [
    ("打印([1, 2, 3][::1.0])", (1, 16)),
    ("设 零 = 0\n打印([1, 2, 3][::零])", (2, 16)),
])
def test_切片步长诊断指向步长表达式(码: str, 期望位置: tuple[int, int]):
    for 登记 in 对拍后端们():
        源 = 源文件(码, "t.cnp")
        程, 袋 = 解析(源)
        检查(程, 袋)
        assert not 袋.有错
        登记.后端类().执行(程, 源, 袋)
        assert 袋.有错
        诊 = 袋.条目[-1]
        assert 诊.码 == "CN0303"
        assert (诊.跨.起.行, 诊.跨.起.列) == 期望位置, 登记.名称


# ==================== 组合使用 ====================

def test_切片_遍历与长度():
    码 = '''设 a = [1, 2, 3, 4, 5]
设 后半 = a[2:]
打印(长度(后半))
遍历 后半 每个 x
    打印(x)'''
    assert 对拍(码) == ["3", "3", "4", "5"]


def test_切片_嵌套列表():
    码 = '''设 m = [[1, 2], [3, 4], [5, 6]]
设 头两行 = m[0:2]
打印(头两行[1][0])'''
    assert 对拍(码) == ["3"]
