"""LSP 阶段 3 收尾：补全 / 悬停 / 跳转定义。

纯函数层测试（不 起 server，直接调 server.py 里的逻辑函数）。
"""
import sys
from pathlib import Path

import pytest

pygls = pytest.importorskip("lsprotocol")  # 无 pygls 的环境跳过

sys.path.insert(0, str(Path(__file__).parents[1]))
from cnplus.lsp import 补全 as 补全模块
from cnplus.lsp import 悬停 as 悬停模块
from cnplus.lsp import 跳转 as 跳转模块


# ==================== 补全 ====================

def test_补全_关键字():
    项们 = 补全模块.补全于("如", 1, 2)  # 光标在「如」后
    名单 = [i.label for i in 项们]
    assert "如果" in 名单
    # 前缀过滤：敲「如」时不再给「循环」等无关候选
    assert "循环" not in 名单


def test_补全_空上下文给全部():
    项们 = 补全模块.补全于("", 1, 1)
    名单 = [i.label for i in 项们]
    assert "如果" in 名单 and "打印" in 名单


def test_补全_覆盖关键字表全部写法():
    from cnplus.lexer.tokens import 关键字映射

    名单 = {项.label for 项 in 补全模块.补全于("", 1, 1)}
    assert set(关键字映射()) <= 名单


def test_补全_内置函数():
    项们 = 补全模块.补全于("打", 1, 1)
    名单 = [i.label for i in 项们]
    assert "打印" in 名单


def test_补全_作用域变量():
    码 = '设 成绩 = 90\n设 名字 = "小明"\n成'
    项们 = 补全模块.补全于(码, 3, 1)
    名单 = [i.label for i in 项们]
    assert "成绩" in 名单
    assert "名字" in 名单


def test_补全_函数与类():
    码 = '函数 算等级(分)\n    返回 分\n类 学生\n    初始化(名字)\n算'
    项们 = 补全模块.补全于(码, 5, 1)
    名单 = [i.label for i in 项们]
    assert "算等级" in 名单


def test_补全_成员方法():
    码 = '设 名单 = [1]\n名单.追'
    项们 = 补全模块.补全于(码, 2, 4)
    名单 = [i.label for i in 项们]
    assert "追加" in 名单


def test_补全_形参遮蔽顶层名字():
    码 = '设 名字 = "顶层"\n函数 取值(名字)\n    名'
    项们 = 补全模块.补全于(码, 3, 6)
    同名 = [项 for 项 in 项们 if 项.label == "名字"]
    assert len(同名) == 1
    assert 同名[0].detail == "参数"


def test_补全_空函数体仍保留形参():
    码 = '函数 示例(名字)\n    '
    同名 = [项 for 项 in 补全模块.补全于(码, 2, 5) if 项.label == "名字"]
    assert len(同名) == 1 and 同名[0].detail == "参数"


@pytest.mark.parametrize("码, 行", [
    ('函数 示例(名字)\n    \n    打印(名字)', 2),
    ('函数 示例(名字)\n    打印(名字)\n    ', 3),
])
def test_补全_函数体首尾空白仍保留形参(码, 行):
    同名 = [项 for 项 in 补全模块.补全于(码, 行, 5) if 项.label == "名字"]
    assert len(同名) == 1 and 同名[0].detail == "参数"


def test_补全和悬停遵循用户名字遮蔽内置名():
    码 = '设 打印 = 1\n打'
    同名 = [项 for 项 in 补全模块.补全于(码, 2, 2) if 项.label == "打印"]
    assert len(同名) == 1
    assert 同名[0].detail == "变量"
    文本 = 悬停模块.悬停于('设 打印 = 1\n打印', 2, 1)
    assert 文本 and 文本.startswith("变量 **打印**")


# ==================== 悬停 ====================

def test_悬停_内置函数():
    码 = '打印("你好")'
    位置 = (1, 1)  # 「打」
    文本 = 悬停模块.悬停于(码, *位置)
    assert 文本 and "打印" in 文本


def test_悬停_变量():
    码 = '设 成绩 = 90\n打印(成绩)'
    文本 = 悬停模块.悬停于(码, 2, 4)  # 「成」处（列 1 起）
    assert 文本 and "成绩" in 文本


def test_悬停_关键字():
    码 = '如果 真\n    打印(1)'
    文本 = 悬停模块.悬停于(码, 1, 1)
    assert 文本 and ("如果" in 文本 or "条件" in 文本)


def test_悬停_形参遮蔽顶层名字():
    码 = '设 名字 = "顶层"\n函数 取值(名字)\n    返回 名字'
    文本 = 悬停模块.悬停于(码, 3, 8)
    assert 文本 and "参数 **名字**" in 文本 and "第 2 行" in 文本


# ==================== 跳转定义 ====================

def test_跳转_变量():
    码 = '设 成绩 = 90\n打印(成绩)'
    位置 = 跳转模块.定义于(码, 2, 4)
    assert 位置 == (1, 3)  # 指向名字本身，不是「设」


def test_跳转_函数():
    码 = '函数 算等级(分)\n    返回 分\n打印(算等级(80))'
    位置 = 跳转模块.定义于(码, 3, 4)  # 算 的位置
    assert 位置 == (1, 4)


def test_跳转_类():
    码 = '类 学生\n    初始化(名字)\n设 甲 = 学生("小明")'
    位置 = 跳转模块.定义于(码, 3, 7)  # 学 的位置
    assert 位置 == (1, 3)


def test_跳转_未定义返回None():
    码 = '打印(未知)'
    assert 跳转模块.定义于(码, 1, 4) is None


def test_跳转_形参遮蔽顶层名字():
    码 = '设 名字 = "顶层"\n函数 取值(名字)\n    返回 名字'
    位置 = 跳转模块.定义于(码, 3, 8)
    assert 位置 == (2, 7)


def test_跳转_局部变量只在声明后可见():
    码 = ('函数 示例()\n'
         '    打印(稍后)\n'
         '    设 稍后 = 1\n'
         '    打印(稍后)')
    assert 跳转模块.定义于(码, 2, 8) is None
    assert 跳转模块.定义于(码, 4, 8) == (3, 7)


def test_跳转_遍历变量只在遍历体内可见():
    码 = ('函数 示例(项们)\n'
         '    遍历 项们 每个 项\n'
         '        打印(项)\n'
         '    打印(项)')
    assert 跳转模块.定义于(码, 3, 12) == (2, 14)
    assert 跳转模块.定义于(码, 4, 8) is None


def test_跳转_顶层遍历变量只在遍历体内可见():
    码 = ('遍历 [1] 每个 项\n'
         '    打印(项)\n'
         '打印(项)')
    assert 跳转模块.定义于(码, 2, 8) == (1, 11)
    assert 跳转模块.定义于(码, 3, 4) is None


def test_跳转_捕获变量只在捕获体内可见():
    码 = ('尝试\n'
         '    抛出 "坏了"\n'
         '捕获 错\n'
         '    打印(错)\n'
         '打印(错)')
    assert 跳转模块.定义于(码, 4, 8) == (3, 4)
    assert 跳转模块.定义于(码, 5, 4) is None


def test_跳转_尝试块局部变量不泄漏():
    码 = ('尝试\n'
         '    设 暂存 = 1\n'
         '    打印(暂存)\n'
         '最后\n'
         '    打印("结束")\n'
         '打印(暂存)')
    assert 跳转模块.定义于(码, 3, 8) == (2, 7)
    assert 跳转模块.定义于(码, 6, 4) is None


def test_跳转_条件块局部变量不泄漏():
    码 = ('如果 真\n'
         '    设 块内 = 1\n'
         '    打印(块内)\n'
         '打印(块内)')
    assert 跳转模块.定义于(码, 3, 8) == (2, 7)
    assert 跳转模块.定义于(码, 4, 4) is None


def test_跳转_类方法形参各自属于所在方法():
    码 = ('类 示例\n'
         '    初始化(名字)\n'
         '        打印(名字)\n'
         '    函数 取值(名字)\n'
         '        返回 名字')
    assert 跳转模块.定义于(码, 3, 12) == (2, 9)
    assert 跳转模块.定义于(码, 5, 12) == (4, 11)


def test_跳转_类方法可以引用当前类名():
    码 = ('类 示例\n'
         '    函数 新建()\n'
         '        返回 示例()')
    assert 跳转模块.定义于(码, 3, 12) == (1, 3)


def test_跳转_嵌套类遵循外层作用域():
    码 = ('函数 外层()\n'
         '    类 内部\n'
         '        函数 新建()\n'
         '            返回 内部()\n'
         '    返回 内部()\n'
         '打印(内部)')
    assert 跳转模块.定义于(码, 4, 16) == (2, 7)
    assert 跳转模块.定义于(码, 5, 8) == (2, 7)
    assert 跳转模块.定义于(码, 6, 4) is None


def test_跳转_嵌套函数遵循外层作用域():
    码 = ('函数 外层()\n'
         '    函数 内层(值)\n'
         '        返回 内层(值)\n'
         '    返回 内层(1)\n'
         '打印(内层)')
    assert 跳转模块.定义于(码, 3, 12) == (2, 8)
    assert 跳转模块.定义于(码, 4, 8) == (2, 8)
    assert 跳转模块.定义于(码, 5, 4) is None


def test_跳转_顶层函数允许前向引用():
    码 = ('函数 先调用()\n'
         '    返回 后声明()\n'
         '函数 后声明()\n'
         '    返回 1')
    assert 跳转模块.定义于(码, 2, 8) == (3, 4)


def test_跳转_函数默认值使用外层作用域():
    码 = ('设 名字 = "外层"\n'
         '函数 取值(名字=名字)\n'
         '    返回 名字')
    assert 跳转模块.定义于(码, 2, 10) == (1, 3)
    assert 跳转模块.定义于(码, 3, 8) == (2, 7)


def test_跳转_多重声明落到各自名字():
    码 = '设 甲, 乙 = [1, 2]\n打印(甲, 乙)'
    assert 跳转模块.定义于(码, 2, 4) == (1, 3)
    assert 跳转模块.定义于(码, 2, 7) == (1, 6)


def test_跳转_导入别名落到别名本身():
    码 = '导入 "json" 作为 工具\n打印(工具)'
    assert 跳转模块.定义于(码, 2, 4) == (1, 14)


def test_无别名导入使用模块末段作为名字():
    码 = '导入 "包.模块"\n模'
    同名 = [项 for 项 in 补全模块.补全于(码, 2, 2) if 项.label == "模块"]
    assert len(同名) == 1 and 同名[0].detail == "导入"
    文本 = 悬停模块.悬停于('导入 "包.模块"\n模块', 2, 1)
    assert 文本 and 文本.startswith("导入 **模块**")
    assert 跳转模块.定义于('导入 "包.模块"\n打印(模块)', 2, 4) == (1, 4)


def test_跳转_定义范围覆盖完整名字():
    码 = '函数 算等级(分)\n    返回 分\n打印(算等级(80))'
    跨 = 跳转模块.定义跨度于(码, 3, 4)
    assert 跨 is not None
    assert (跨.起.行, 跨.起.列, 跨.止.行, 跨.止.列) == (1, 4, 1, 7)
