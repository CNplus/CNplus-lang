def _收集名字(程) -> list[tuple[str, str]]:
    """收集顶层可见的名字：(名字, 类型标签)。"""
    出 = []
    for s in 程.语句们:
        if isinstance(s, 声明语句):
            出.append((s.名, "变量"))
        elif isinstance(s, 多重声明语句):
            for n in s.名们:
                出.append((n, "变量"))
        elif isinstance(s, 函数声明):
            出.append((s.名, "函数"))
        elif isinstance(s, 类声明):
            出.append((s.名, "类"))
    return 出


def _光标前缀(码: str, 行: int, 列: int) -> tuple[str, str]:
    """取光标处的输入前缀和行的开头部分。

    返回 (行开头, 正在敲的词)——正在敲的词从中断处截断。
    """
    行们 = 码.split("\n")
    当前行 = 行们[行 - 1] if 0 < 行 <= len(行们) else ""
    前 = 当前行[:列 - 1] if 0 < 列 <= len(当前行) + 1 else 当前行
    # 找正在敲的词（标识符字符集：中文+字母+数字）
    词 = ""
    for 字 in reversed(前):
        if 字.isalnum() or 字 == "_":
            词 = 字 + 词
        else:
            break
    开头 = 前[: len(前) - len(词)]
    return 开头, 词


def 补全于(码: str, 行: int, 列: int) -> list[lsp.CompletionItem]:
    """光标处给补全候选。行/列 1 起。"""
    开头, 词 = _光标前缀(码, 行, 列)
    候选: list[tuple[str, str, str]] = []  # (名字, 种类, 说明)

    # 成员方法：xxx.词 —— 给集合方法
    if 开头.endswith("."):
        前缀对象 = 开头[:-1].rstrip()
        对象词 = ""
        for 字 in reversed(前缀对象):
            if 字.isalnum() or 字 in "_»]":
                对象词 = 字 + 对象词
            else:
                break
        for 名, 说明 in 内置说明.items():
            if 名 in ("追加", "插入", "移除", "弹出", "排序", "倒序",
                      "包含", "连接", "长度", "所有标签", "所有值",
                      "有标签", "删标签", "分割", "替换", "查找",
                      "去空白", "大写", "小写", "开头是", "结尾是"):
                候选.append((名, "方法", 说明))
    else:
        # 关键字 + 内置 + 作用域名
        for 写法, 种 in 关键字映射().items():
            if 写法 in 关键字说明:
                候选.append((写法, "关键字", 关键字说明[写法]))
        for 名, 说明 in 内置说明.items():
            候选.append((名, "函数", 说明))
        源 = 源文件(码, "<补全>")
        程, 袋 = 解析(源)
        for 名, 标签 in _收集名字(程):
            候选.append((名, 标签, ""))

    # 按前缀过滤
    if 词:
        候选 = [c for c in 候选 if c[0].startswith(词)]

    项们 = []
    for 名, 种类, 说明 in 候选:
        项们.append(lsp.CompletionItem(
            label=名,
            kind={"关键字": lsp.CompletionItemKind.Keyword,
                  "函数": lsp.CompletionItemKind.Function,
                  "方法": lsp.CompletionItemKind.Method,
                  "变量": lsp.CompletionItemKind.Variable,
                  "类": lsp.CompletionItemKind.Class}[种类],
            detail=种类,
            documentation=说明 or None,
        ))
    return 项们
